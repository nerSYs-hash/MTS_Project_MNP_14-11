/**
 * Очистить телефонный номер до цифр (10 или 11 цифр)
 */
export function cleanPhoneNumber(phone: string): string {
  const digits = phone.replace(/\D/g, '');
  if (digits.length === 11 && (digits.startsWith('7') || digits.startsWith('8'))) {
    return '7' + digits.slice(1);
  }
  if (digits.length === 10) {
    return '7' + digits;
  }
  return digits;
}

/**
 * Преобразовать любой ввод номера телефона в строгий слитный формат 79XXXXXXXXX (11 цифр).
 * Поддерживает:
 * - 79293664010
 * - 7-929-366-40-10
 * - +7 (929) 366-40-10
 * - 89293664010
 * - +7(929)3664010
 * - 8-929-366-40-10
 * - 9293664010
 * Возвращает строгий формат 7XXXXXXXXXX (11 цифр) или null если номер некорректен.
 */
export function cleanToStrictMtsPhone(raw: string): string | null {
  if (!raw) return null;
  const digits = raw.replace(/\D/g, '');
  if (digits.length === 11) {
    if (digits.startsWith('7')) {
      return digits;
    }
    if (digits.startsWith('8')) {
      return '7' + digits.slice(1);
    }
  } else if (digits.length === 10 && digits.startsWith('9')) {
    return '7' + digits;
  }
  return null;
}

/**
 * Отформатировать телефон по маске +7 (XXX) XXX-XX-XX
 * Поддерживает корректное удаление (Backspace): не застревает на скобке и позволяет стирать до +7 и начисто.
 */
export function formatPhoneNumber(value: string): string {
  const digits = value.replace(/\D/g, '');
  if (!digits) return '';

  // Если введено только + или стерто до 7
  if (digits === '7' && value.trim().length <= 2) {
    return '+7';
  }

  let normalized = digits;
  if (normalized.startsWith('8')) {
    normalized = '7' + normalized.slice(1);
  } else if (!normalized.startsWith('7')) {
    normalized = '7' + normalized;
  }

  // Ограничиваем 11 цифрами
  normalized = normalized.slice(0, 11);

  if (normalized.length === 1) {
    return '+7';
  }

  const part1 = normalized.slice(1, 4);
  const part2 = normalized.slice(4, 7);
  const part3 = normalized.slice(7, 9);
  const part4 = normalized.slice(9, 11);

  // Закрывать скобку только если есть дальнейшие цифры ИЛИ если в исходной строке была скобка/пробел
  const shouldCloseParen =
    part1.length === 3 && (part2.length > 0 || value.includes(')') || value.length > 8);

  let formatted = '+7';
  if (part1.length > 0) formatted += ` (${part1}`;
  if (shouldCloseParen) formatted += ')';
  if (part2.length > 0) formatted += ` ${part2}`;
  if (part3.length > 0) formatted += `-${part3}`;
  if (part4.length > 0) formatted += `-${part4}`;

  return formatted;
}

/**
 * Рассчитать точное время перезвона по местным часам клиента (например, в 18:00 по времени абонента).
 * Если указанное время у клиента сегодня уже прошло, перезвон автоматически рассчитывается на завтра в то же время.
 */
export function calculateTargetCallbackTimeByClientHour(
  utcOffset: number,
  targetHour: number,
  targetMinute: number = 0,
  baseDate: Date = new Date()
): {
  targetTimestamp: number;
  minutesFromNow: number;
  isTomorrow: boolean;
  formattedTargetTime: string;
  clientCurrentFormatted: string;
} {
  const safeHour = Math.min(23, Math.max(0, targetHour));
  const safeMinute = Math.min(59, Math.max(0, targetMinute));

  const nowMs = baseDate.getTime();
  const utcMillis = nowMs + baseDate.getTimezoneOffset() * 60000;
  const clientMillis = utcMillis + utcOffset * 3600000;
  const clientDate = new Date(clientMillis);

  const curHour = clientDate.getHours();
  const curMinute = clientDate.getMinutes();
  const curSecond = clientDate.getSeconds();

  const clientMinutesNow = curHour * 60 + curMinute + curSecond / 60;
  const targetMinutes = safeHour * 60 + safeMinute;

  let diffMinutes = targetMinutes - clientMinutesNow;
  let isTomorrow = false;

  // Если целевой час сегодня уже наступил или прошел у клиента
  if (diffMinutes <= 0) {
    diffMinutes += 24 * 60;
    isTomorrow = true;
  }

  const roundedMinutes = Math.max(1, Math.round(diffMinutes));
  const targetTimestamp = nowMs + roundedMinutes * 60 * 1000;

  const formattedTargetTime = `${String(safeHour).padStart(2, '0')}:${String(safeMinute).padStart(2, '0')}`;
  const clientCurrentFormatted = `${String(curHour).padStart(2, '0')}:${String(curMinute).padStart(2, '0')}`;

  return {
    targetTimestamp,
    minutesFromNow: roundedMinutes,
    isTomorrow,
    formattedTargetTime,
    clientCurrentFormatted,
  };
}

/**
 * Найти регион и часовой пояс по телефонному номеру
 * с приоритетом наиболее длинного (точного 5- или 4-значного) DEF-префикса.
 */
export function findRegionByPhone(phone: string): RegionInfo | null {
  const cleaned = cleanPhoneNumber(phone);
  if (cleaned.length < 4) return null;

  // Извлекаем номер после кода страны 7 (например, 9122, 982, 908)
  const code = cleaned.slice(1);

  let bestMatch: { region: RegionInfo; prefixLen: number } | null = null;

  for (const region of RUSSIAN_REGIONS) {
    for (const prefix of region.defPrefixes) {
      if (code.startsWith(prefix)) {
        if (!bestMatch || prefix.length > bestMatch.prefixLen) {
          bestMatch = { region, prefixLen: prefix.length };
        }
      }
    }
  }

  if (bestMatch) {
    return bestMatch.region;
  }

  // Если точного 4-5 значного префикса не нашлось, используем макрорегиональные правила
  if (code.startsWith('916') || code.startsWith('925') || code.startsWith('926') || code.startsWith('985') || code.startsWith('977')) {
    return RUSSIAN_REGIONS.find((r) => r.city === 'Москва') || null;
  }
  if (code.startsWith('978') || code.startsWith('979')) {
    return RUSSIAN_REGIONS.find((r) => r.city === 'Симферополь') || null;
  }
  if (code.startsWith('949')) {
    return RUSSIAN_REGIONS.find((r) => r.city === 'Донецк') || null;
  }
  if (code.startsWith('959')) {
    return RUSSIAN_REGIONS.find((r) => r.city === 'Луганск') || null;
  }
  if (code.startsWith('990')) {
    return RUSSIAN_REGIONS.find((r) => r.city === 'Мелитополь') || null;
  }

  return null;
}

/**
 * Найти регион по названию города, региона, республики или синониму (алиасу)
 */
export function findRegionByCity(cityInput: string): RegionInfo | null {
  const query = cityInput.trim().toLowerCase();
  if (!query) return null;

  // 1. Точное совпадение с названием города
  const exactCity = RUSSIAN_REGIONS.find((r) => r.city.toLowerCase() === query);
  if (exactCity) return exactCity;

  // 2. Точное совпадение с одним из алиасов (СПб, Питер, Кузбасс, Югра, Челны и т.д.)
  const exactAlias = RUSSIAN_REGIONS.find(
    (r) => r.aliases && r.aliases.some((a) => a.toLowerCase() === query)
  );
  if (exactAlias) return exactAlias;

  // 3. Город начинается с введенной строки (например "новосиб" -> Новосибирск)
  const cityStartsWith = RUSSIAN_REGIONS.find((r) => r.city.toLowerCase().startsWith(query));
  if (cityStartsWith) return cityStartsWith;

  // 4. Алиас начинается с введенной строки
  const aliasStartsWith = RUSSIAN_REGIONS.find(
    (r) => r.aliases && r.aliases.some((a) => a.toLowerCase().startsWith(query))
  );
  if (aliasStartsWith) return aliasStartsWith;

  // 5. Вхождение в название города, региона или алиаса
  return (
    RUSSIAN_REGIONS.find(
      (r) =>
        r.city.toLowerCase().includes(query) ||
        r.regionName.toLowerCase().includes(query) ||
        (r.aliases && r.aliases.some((a) => a.toLowerCase().includes(query)))
    ) || null
  );
}

/**
 * Получить текущее местное время клиента по его UTC смещению
 */
export function getClientLocalTime(utcOffset: number, baseDate: Date = new Date()): {
  formattedTime: string;
  hour: number;
  minute: number;
} {
  const utcMillis = baseDate.getTime() + baseDate.getTimezoneOffset() * 60000;
  const clientMillis = utcMillis + utcOffset * 3600000;
  const clientDate = new Date(clientMillis);

  const hour = clientDate.getHours();
  const minute = clientDate.getMinutes();

  const formattedTime = `${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`;

  return {
    formattedTime,
    hour,
    minute,
  };
}

/**
 * Проверить, разрешено ли звонить абоненту по закону и регламенту (08:00 - 21:00)
 */
export function isCallingTimeAllowed(utcOffset: number, baseDate: Date = new Date()): {
  allowed: boolean;
  clientTimeStr: string;
  hour: number;
  statusText: string;
} {
  const { formattedTime, hour } = getClientLocalTime(utcOffset, baseDate);
  const allowed = hour >= 8 && hour < 21;

  let statusText = 'Разрешено звонить (день)';
  if (hour >= 21 || hour < 6) {
    statusText = 'Ночное время абонента! Звонок запрещён';
  } else if (hour >= 6 && hour < 8) {
    statusText = 'Раннее утро у абонента. Рекомендуется подождать до 08:00';
  }

  return {
    allowed,
    clientTimeStr: formattedTime,
    hour,
    statusText,
  };
}
